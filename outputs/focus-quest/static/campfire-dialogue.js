  function staticLines(character, topic) {
    return scripts[character][topic].map(([title, text], index) => ({
      id: `campfire:${character}:${topic}:${String(index + 1).padStart(2, '0')}`,
      character, topic, title, text, tone: topic === 'relax' ? 'rest' : 'neutral',
    }));
  }

  function buildLines(state, characterId = 'guide', topic = 'relax') {
    const character = characters.some(item => item.id === characterId) ? characterId : 'guide';
    topic = topics.includes(topic) ? topic : 'relax';
    const lines = staticLines(character, topic);
    if (character !== 'guide' || topic !== 'advice') return lines;

    state = state && typeof state === 'object' ? state : {};
    const provider = getAdvice();
    if (!provider || typeof provider.buildLines !== 'function') return lines;
    const current = Boolean(state.date && state.date === state.today);
    const main = state.advice || {};
    const totals = state.totals || {};
    const complete = current && (main.id === 'complete'
      || (Number(totals.target) > 0 && Number(totals.minutes) >= Number(totals.target)));
    const resting = current && (main.tone === 'rest' || complete);
    const ids = new Set(lines.map(line => line.id));
    for (const line of provider.buildLines(state)) {
      if (!line || typeof line.id !== 'string' || typeof line.text !== 'string' || !line.text.trim()) continue;
      // Keep practical, record-based advice; the original module's NPC filler
      // would duplicate these characters' own conversation pools.
      if (!/^(main:|subject:|activity:|weekly:)/.test(line.id)) continue;
      if (!current && /今天|今日/.test(`${line.title || ''}${line.text}`)) continue;
      if (resting && line.tone !== 'rest' && line.id !== 'weekly:progress'
          && !(complete && line.id === 'main:complete')) continue;
      const id = `campfire:guide:state:${line.id}`;
      if (ids.has(id)) continue;
      ids.add(id);
      lines.push({id, character: 'guide', topic: 'advice', title: String(line.title || '聊聊安排'),
        text: line.text, tone: typeof line.tone === 'string' ? line.tone : 'neutral'});
    }
    return lines;
  }

  function pickLine(lines, recentIds = [], random = Math.random) {
    if (!Array.isArray(lines)) return null;
    const ids = new Set();
    const valid = lines.filter(line => {
      if (!line || typeof line.id !== 'string' || !line.id || typeof line.text !== 'string'
          || !line.text.trim() || ids.has(line.id)) return false;
      ids.add(line.id);
      return true;
    });
    if (!valid.length) return null;
    const recent = (Array.isArray(recentIds) ? recentIds : typeof recentIds === 'string' ? [recentIds] : [])
      .filter(id => typeof id === 'string').slice(-8);
    let pool = valid.filter(line => !recent.includes(line.id));
    if (!pool.length) {
      const oldest = Math.min(...valid.map(line => recent.lastIndexOf(line.id)));
      pool = valid.filter(line => recent.lastIndexOf(line.id) === oldest);
    }
    const sample = Number((typeof random === 'function' ? random : Math.random)());
    const bounded = Number.isFinite(sample) ? Math.min(Math.max(sample, 0), 1) : 0;
    return pool[Math.min(pool.length - 1, Math.floor(bounded * pool.length))];
  }

  return {characters, buildLines, pickLine};
